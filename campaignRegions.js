const RIVER_CROSSINGS = [["naru", "savo"]];

// ------------------------------------------------------------
// 회차(run) 단위 구역 상태 — state.run.campaign 에 넣어 사용
// 회귀 시 createCampaignState()로 통째로 새로 만들면 됨
// status: "locked" | "available" | "secured"
// ------------------------------------------------------------
function createCampaignState() {
    const regions = {};
    for (const id in REGIONS) {
        regions[id] = { status: "locked", nodeGraphSeed: null };
    }
    regions[CAMPAIGN_MAP.startRegionId].status = "available";
    return { currentRegionId: null, regions };
}

// 구역 확보 → 인접한 locked 구역을 available로 해금
function secureRegion(campaign, regionId) {
    campaign.regions[regionId].status = "secured";
    const unlocked = [];
    for (const nid of REGIONS[regionId].neighbors) {
        if (campaign.regions[nid].status === "locked") {
            campaign.regions[nid].status = "available";
            unlocked.push(nid);
        }
    }
    return unlocked;
}

function isRiverCrossing(a, b) {
    return RIVER_CROSSINGS.some(([x, y]) => (x === a && y === b) || (x === b && y === a));
}

function getRegionName(id, lang = "ko") {
    return REGIONS[id].name[lang] ?? REGIONS[id].name.ko;
}
